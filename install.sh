#!/bin/bash
set -e

echo "Updating system package lists..."
sudo apt update && sudo apt upgrade -y

echo "Installing core prerequisites (git, curl, build-essential)..."
sudo apt install -y curl git build-essential

echo "Installing Node.js LTS..."
if ! command -v node &> /dev/null; then
    curl -fsSL https://deb.nodesource.com/setup_lts.x | sudo -E bash -
    sudo apt install -y nodejs
else
    echo "Node.js is already installed ($(node -v))."
fi

echo "Installing Electron system runtime libraries..."
sudo apt install -y \
    libglib2.0-0t64 \
    libnss3 \
    libnspr4 \
    libatk1.0-0 \
    libatk-bridge2.0-0 \
    libcups2 \
    libdrm2 \
    libdbus-1-3 \
    libexpat1 \
    libfontconfig1 \
    libgbm1 \
    libgdk-pixbuf-2.0-0 \
    libpango-1.0-0 \
    libpangocairo-1.0-0 \
    libx11-6 \
    libx11-xcb1 \
    libxcb1 \
    libxcomposite1 \
    libxcursor1 \
    libxdamage1 \
    libxext6 \
    libxfixes3 \
    libxi6 \
    libxrandr2 \
    libxrender1 \
    libxss1 \
    libxtst6 \
    libasound2

echo "Installing project NPM dependencies..."
npm install

echo "Moonitor-Kiosk installation completed successfully!"